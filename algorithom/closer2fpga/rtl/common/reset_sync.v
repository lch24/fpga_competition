`timescale 1ns / 1ps
//==============================================================================
// reset_sync.v — 复位同步器（异步复位、同步释放）
//------------------------------------------------------------------------------
// 团队规范（README 第3节）：低有效复位 rst_n，同步释放。
// 每个时钟域各自例化一个本模块；跨域复位必须经过本模块，禁止直接使用
// 异步复位信号驱动该域的寄存器。
//
// 接口：
//   clk       : 目标时钟域时钟
//   arst_n    : 异步复位输入（低有效）。拉低立即复位输出；释放时刻与 clk 无对齐要求。
//   rst_n     : 同步释放后的复位输出（低有效）。
//
// 复位行为：
//   arst_n==0 期间 rst_n 立即为 0（异步生效，不等待时钟）。
//   arst_n 释放后，rst_n 在 clk 上升沿再经过 2 拍同步器后拉高（同步释放）。
//   2 级同步器用于消除亚稳态。
//
// 验证提示：复位释放后至少再等 1 拍（rst_n 为高）后才允许发起有效事务。
//==============================================================================
module reset_sync (
    input  wire clk,
    input  wire arst_n,
    output wire rst_n
);

    reg [1:0] sync_ff;

    always @(posedge clk or negedge arst_n) begin
        if (!arst_n)
            sync_ff <= 2'b00;
        else
            sync_ff <= {sync_ff[0], 1'b1};
    end

    assign rst_n = sync_ff[1];

endmodule
