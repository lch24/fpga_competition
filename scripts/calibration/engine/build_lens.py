"""Scalar lens regularizer/feasibility microprogram, called after residual HOST.

q0..q33 are scratch, disjoint from LM loop variables and all residual buffers.
Only the existing FP service and RAM are used. The four extra residuals belong
to global camera columns; pose columns remain view-local and exactly zero here.
"""


def append_program(p):
    e, L = p.emit, p.label
    L('lens_objective')
    p.il(0, 'trial')
    for i in range(9):
        e(f'LD F0,A0,{i}')
        p.st(f'q{i}')
    for i in (0, 1): p.unary(f'q{i}', 'FEXP', f'q{i}')
    p.fbin('q2','FMUL','q2','fwidth')
    p.fbin('q3','FMUL','q3','fheight')
    # Radius of a disk enclosing the entire output rectangle, in lens units.
    for axis, dim in ((0,'fwidth'), (1,'fheight')):
        center=f'q{2+axis}'
        radius=f'q{axis}'
        p.fbin('q14','FSUB',dim,'one')
        p.fbin('q14','FSUB','q14',center)
        p.unary('q14','FABS','q14')
        p.unary('q15','FABS',center)
        selected=p.unique('field_extent')
        p.fb('q14',6,'q15',selected)
        p.fcopy('q14','q15')
        L(selected)
        p.fbin(radius,'FDIV','q14',radius)
        p.fbin(radius,'FMUL',radius,radius)
    p.fbin('q9','FADD','q0','q1')
    p.fbin('q14','FMUL','q6','q6')
    p.fbin('q15','FMUL','q7','q7')
    p.fbin('q14','FADD','q14','q15')
    p.fbin('q14','FMUL','q14','q9')
    p.unary('q10','FSQRT','q14')
    p.fbin('q10','FMUL','six','q10')
    p.fbin('q14','FMUL','q9','q9')
    p.fbin('q12','FMUL','q5','q14')
    p.fbin('q14','FMUL','q14','q9')
    p.fbin('q13','FMUL','q8','q14')
    p.fbin('q12','FMUL','two','q12')
    p.fbin('q14','FMUL','three','q13')
    p.fbin('q12','FADD','q12','q14')
    p.fbin('q12','FMUL','q12','lens_weight')
    p.fbin('q13','FMUL','q13','sqrt_three')
    p.fbin('q13','FMUL','q13','lens_weight')
    # Radial Jacobian eigenvalues: gain and radial derivative. Bound the
    # tangential perturbation's smallest eigenvalue by -6*r*hypot(p1,p2).
    for coefficient, src in ((16,4),(17,5),(18,8)): p.fcopy(f'q{coefficient}',f'q{src}')
    e('CALL lens_cubic_min')
    p.fbin('q19','FSUB','q21','q10')
    p.fbin('q16','FMUL','q4','three')
    p.fbin('q17','FMUL','q5','five')
    p.fbin('q18','FMUL','q8','seven')
    e('CALL lens_cubic_min')
    p.fbin('q20','FSUB','q21','q10')
    p.fcopy('lens_margin','q19')
    p.fb('q19',4,'q20','lens_margin_ready')
    p.fcopy('lens_margin','q20')
    L('lens_margin_ready')
    p.fcopy('q30','q19')
    e('CALL lens_barrier')
    p.fcopy('q32','q31')
    p.fcopy('q30','q20')
    e('CALL lens_barrier')
    p.il(0,'svc_dst')
    p.il(1,'data_nr')
    e('IADD A0,A0,A1')
    p.ld(4,'zero')
    for offset,src in enumerate(('q12','q13','q32','q31')):
        p.ld(0,src)
        e(f'ST F0,A0,{offset}','FMUL F0,F0,F0','FADD F4,F4,F0')
    p.ld(0,'svc_cost')
    e('FADD F0,F0,F4')
    p.st('svc_objective')
    e('RET')

    # min(1+a*z+b*z^2+c*z^3), z in [0, field_radius^2]. Endpoints plus ALL
    # stationary points: unlike a grid, a narrow fold cannot lie between taps.
    L('lens_cubic_min')
    p.fcopy('q21','one')
    p.fcopy('q22','q9')
    e('CALL lens_cubic_eval')
    p.fbin('q24','FMUL','q18','three')
    p.fbin('q25','FMUL','q17','two')
    p.fcopy('q26','q16')
    p.fb('q24',1,'zero','lens_linear')
    p.fbin('q27','FMUL','q25','q25')
    p.fbin('q33','FMUL','q24','q26')
    p.fbin('q33','FMUL','q33','four')
    p.fbin('q27','FSUB','q27','q33')
    p.fb('q27',3,'zero','lens_min_done')
    p.unary('q28','FSQRT','q27')
    p.fb('q25',6,'zero','lens_positive_b')
    p.unary('q28','FNEG','q28')
    L('lens_positive_b')
    p.fbin('q29','FADD','q25','q28')
    p.fbin('q29','FMUL','q29','half')
    p.unary('q29','FNEG','q29')
    p.fb('q29',1,'zero','lens_zero_root')
    p.fbin('q22','FDIV','q29','q24')
    e('CALL lens_cubic_eval')
    p.fbin('q22','FDIV','q26','q29')
    e('CALL lens_cubic_eval','RET')
    L('lens_zero_root')
    p.fbin('q33','FMUL','two','q24')
    p.fbin('q22','FDIV','q25','q33')
    p.unary('q22','FNEG','q22')
    e('CALL lens_cubic_eval','RET')
    L('lens_linear')
    p.fb('q25',1,'zero','lens_min_done')
    p.fbin('q22','FDIV','q26','q25')
    p.unary('q22','FNEG','q22')
    e('CALL lens_cubic_eval')
    L('lens_min_done')
    e('RET')

    L('lens_cubic_eval')
    p.fb('q22',3,'zero','lens_eval_done')
    p.fb('q22',5,'q9','lens_eval_done')
    p.fbin('q23','FMUL','q18','q22')
    p.fbin('q23','FADD','q23','q17')
    p.fbin('q23','FMUL','q23','q22')
    p.fbin('q23','FADD','q23','q16')
    p.fbin('q23','FMUL','q23','q22')
    p.fbin('q23','FADD','q23','one')
    p.fb('q23',6,'q21','lens_eval_done')
    p.fcopy('q21','q23')
    L('lens_eval_done')
    e('RET')

    L('lens_barrier')
    p.fcopy('q31','zero')
    p.fb('q30',6,'barrier_start','lens_barrier_done')
    p.fcopy('q33','q30')
    p.fb('q30',6,'barrier_epsilon','lens_barrier_div')
    p.fcopy('q33','barrier_epsilon')
    L('lens_barrier_div')
    p.fbin('q31','FDIV','barrier_start','q33')
    p.fbin('q31','FSUB','q31','one')
    p.fb('q30',6,'barrier_epsilon','lens_barrier_weight')
    p.fbin('q33','FSUB','barrier_epsilon','q30')
    p.fbin('q33','FMUL','q33','barrier_slope')
    p.fbin('q31','FADD','q31','q33')
    L('lens_barrier_weight')
    p.fbin('q31','FMUL','q31','barrier_weight')
    L('lens_barrier_done')
    e('RET')
