"""Generate RGB565 component Gamma LUTs. No per-pixel power/divide hardware."""
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
GAMMAS=(1.0,0.75,0.5,1.3,2.0)
def mapped(value,bits,curve):
    expanded=(value<<3 | value>>2) if bits==5 else (value<<2 | value>>4)
    corrected=int((expanded/255.0)**GAMMAS[curve]*255.0+0.5)
    return min((1<<bits)-1,corrected>>(8-bits))
def main():
    lines=['// Generated by scripts/image/generate_gamma_tables.py.']
    for bits,name in ((5,'gamma_rb'),(6,'gamma_g')):
        for curve in range(8):
            for value in range(1<<bits):
                result=mapped(value,bits,curve if curve<5 else 0)
                lines.append(f"{name}[{(curve<<bits)|value}]={bits}'d{result};")
    (ROOT/'rtl/include/video_gamma_init.vh').write_text('\n'.join(lines)+'\n',encoding='utf-8')
if __name__=='__main__':main()
